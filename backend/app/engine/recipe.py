"""Engineering artifacts for the recommended configuration.

Everything is rendered from templates and the engine's own numbers; nothing here is executed by
the app. HONEST STATUS: these files have been syntax-checked, not run on a device, and the Jetson
commands use only documented tools (`nvpmodel`, `jetson_clocks`, `tegrastats`, `trtexec`). Mode ids
and fan/clock controls differ per board, so the scripts tell you what to look up instead of guessing.
"""

from __future__ import annotations

