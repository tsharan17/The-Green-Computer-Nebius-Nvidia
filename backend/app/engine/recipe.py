@dataclass(frozen=True)
class RecipeFile:
    description: str
    content: str


def _is_jetson(hw: HardwareProfile) -> bool:
    return "jetson" in hw.name.lower() or "jetson" in hw.id


def _hw_from_input(model: ModelProfile) -> tuple[int, int]:
    m = re.search(r"(\d+)\s*x\s*(\d+)", model.input_desc)
    return (int(m.group(1)), int(m.group(2))) if m else (224, 224)


def _metrics(r: EvaluationResult) -> dict:
    keep = ("latency", "capacity_fps", "power_avg", "energy_per_inference", "temperature",
            "accuracy")  # fmt: skip
    return {
        k: {
            "value": round(r.metrics[k].value, 4),
            "unit": r.metrics[k].unit,
            "best_case": round(r.metrics[k].low, 4),
            "worst_case": round(r.metrics[k].high, 4),
            "source": r.metrics[k].provenance.value,
        }
        for k in keep
    }


def _optimise_model_py(cfg: Config, model: ModelProfile) -> str:
    h, w = _hw_from_input(model)
    h, w = round(h * cfg.resolution_scale / 32) * 32 or 32, round(w * cfg.resolution_scale / 32) * 32 or 32
    notes = []
    if cfg.sparsity > 0:
        notes.append(
            f"# Pruning ({cfg.sparsity:.0%}): do this BEFORE export, in your training framework\n"
            "# (structured channel pruning, e.g. torch-pruning), then fine-tune. Not generated here."
        )
    if cfg.resolution_scale != 1.0:
        notes.append(
            f"# Input resolution: export/run at about {h}x{w} (native x {cfg.resolution_scale:.0%}) and "
            "re-check accuracy."
        )
    notes_text = "\n".join(notes)
    return f'''"""Convert an FP32 ONNX model to {cfg.precision.upper()} for the recommended configuration.

Generated by The Green Computer from the recommended settings. Not run by the app: check the
output loads in your runtime and re-measure accuracy before relying on it.

    pip install onnx onnxconverter-common onnxruntime numpy
    python optimise_model.py --model model_fp32.onnx --out model_{cfg.precision}.onnx \\
        [--calib-dir calibration_npy/]
"""

import argparse
from pathlib import Path

PRECISION = "{cfg.precision}"
{notes_text}


def to_fp16(src: Path, dst: Path) -> None:
    import onnx
    from onnxconverter_common import float16

    model = onnx.load(str(src))
    onnx.save(float16.convert_float_to_float16(model, keep_io_types=True), str(dst))


def to_int8(src: Path, dst: Path, calib_dir: Path | None) -> None:
    import numpy as np
    import onnxruntime as ort
    from onnxruntime.quantization import CalibrationDataReader, QuantType, quantize_static

    sess = ort.InferenceSession(str(src), providers=["CPUExecutionProvider"])
    inp = sess.get_inputs()[0]
    shape = [1 if not isinstance(d, int) else d for d in inp.shape]
    files = sorted(calib_dir.glob("*.npy")) if calib_dir else []
    if not files:
        print("WARNING: no calibration data given; INT8 scales will be poor. Use 100-500 real inputs.")

    class Reader(CalibrationDataReader):
        def __init__(self):
            self.i = 0

        def get_next(self):
            if self.i >= max(len(files), 16):
                return None
            x = (
                np.load(files[self.i]).astype(np.float32)
                if files
                else np.random.rand(*shape).astype(np.float32)
            )
            self.i += 1
            return {{inp.name: x.reshape(shape)}}

    quantize_static(str(src), str(dst), Reader(), weight_type=QuantType.QInt8,
                    activation_type=QuantType.QInt8)


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--model", required=True, type=Path)
    ap.add_argument("--out", required=True, type=Path)
    ap.add_argument("--calib-dir", type=Path, default=None)
    a = ap.parse_args()
    if PRECISION == "fp16":
        to_fp16(a.model, a.out)
    elif PRECISION == "int8":
        to_int8(a.model, a.out, a.calib_dir)
    else:
        a.out.write_bytes(a.model.read_bytes())
    print("wrote", a.out)


if __name__ == "__main__":
    main()
'''


def _build_engine_sh(cfg: Config, model: ModelProfile) -> str:
    h, w = _hw_from_input(model)
    h, w = round(h * cfg.resolution_scale / 32) * 32 or 32, round(w * cfg.resolution_scale / 32) * 32 or 32
    flag = {"fp16": "--fp16", "int8": "--int8", "fp32": ""}[cfg.precision]
    return f"""#!/usr/bin/env bash
# Build a TensorRT engine on the Jetson for the recommended configuration.
# Generated, not run. Check `trtexec --help` for your JetPack version's flags and the input name.
set -euo pipefail
ONNX="${{1:-model_{cfg.precision}.onnx}}"
trtexec --onnx="$ONNX" --saveEngine=model_{cfg.precision}.plan {flag} \\
  --shapes=input:{cfg.batch}x3x{h}x{w}
"""


def _power_sh(cfg: Config, hw: HardwareProfile) -> str:
    mode = hw.mode(cfg.power_mode_id)
    clock = (
        f"# Clock cap: {cfg.clock_trim:.0%} of the mode's clocks. Jetson exposes this through the\n"
        "# nvpmodel config (/etc/nvpmodel.conf) or devfreq max_freq files; look up your board's files.\n"
        if cfg.clock_trim != 1.0
        else ""
    )
    return f"""#!/usr/bin/env bash
# Set the recommended power mode: {mode.name} (cap about {mode.cap_w:.0f} W).
# Generated, not run. The numeric id differs per Jetson module: list them first.
set -euo pipefail
sudo nvpmodel -q                    # shows the current mode
grep -n "POWER_MODEL" /etc/nvpmodel.conf   # find the id whose name matches "{cfg.power_mode_id}"
# sudo nvpmodel -m <ID>             # <- put that id here, then run again
{clock}sudo jetson_clocks --show    # confirm the resulting clocks
"""


def _verify_sh(spec: ProjectSpec, cfg: Config) -> str:
    return f"""#!/usr/bin/env bash
# Measure the recommended configuration on the real board and send it back to The Green Computer.
# Generated, not run. Run your workload in another terminal while this logs for 60 s.
set -euo pipefail
APP="${{APP:-http://localhost:8000}}"
tegrastats --interval 1000 --logfile tegrastats.log &
TPID=$!
sleep 60
kill $TPID || true
curl -s -X POST \\
  "$APP/api/v1/measurements/import?format=tegrastats&device_id={spec.device_id}&model_id={spec.model_id}&precision={cfg.precision}&batch={cfg.batch}&ambient_c={spec.workload.ambient_c}" \\
  --data-binary @tegrastats.log
echo
echo "Now add your measured latency/throughput on the Verify tab to calibrate the model."
"""


def _design_notes(
    spec: ProjectSpec, hw: HardwareProfile, res: OptimisationResult
) -> str:
    r = res.best or res.baseline
    cfg = r.config
    cool = hw.cooling(cfg.cooling_id)
    p = r.metrics["power_avg"].value
    amb = spec.workload.ambient_c
    r_max = (hw.t_throttle_c - amb) / p if p > 0 else float("inf")
    mode = hw.mode(cfg.power_mode_id)
    lines = [
        f"# Hardware design notes: {hw.name}",
        "",
        "For hardware, board, power and thermal engineers. All numbers are analytical predictions "
        "from The Green Computer's L0 model (see the assumptions document); none is measured unless "
        "marked so.",
        "",
        "## Power budget for the recommended configuration",
        "",
        "| Term | Value |",
        "|---|---|",
        f"| Power mode | {mode.name} (cap about {mode.cap_w:.0f} W) |",
        f"| Average power at {spec.workload.fps:.0f} frames/s | {p:.1f} W "
        f"(best case {r.metrics['power_avg'].low:.1f}, worst case {r.metrics['power_avg'].high:.1f}) |",
        f"| Peak (busy) power | {r.metrics['power_peak'].value:.1f} W |",
        f"| Idle / static floor | {hw.idle_w + cool.fan_w:.1f} W |",
        f"| Leakage at 25 °C | {hw.leak_w_25c:.1f} W (grows about 1.5% per °C) |",
        "",
        "## Thermal requirement",
        "",
        f"At {amb:.0f} °C ambient and {p:.1f} W average, staying under the {hw.t_throttle_c:.0f} °C "
        f"throttle point needs a total thermal resistance of at most **{r_max:.2f} K/W**; "
        f"the selected cooling ('{cool.name}') is modelled at {cool.r_th_k_per_w:.2f} K/W. "
        f"Predicted steady temperature: {r.metrics['temperature'].value:.0f} °C "
        f"(worst case {r.metrics['temperature'].high:.0f} °C).",
        "",
        "## What limits this workload",
        "",
        res.limiting_factor or "Not determined.",
        "",
        "## Design what-ifs (one parameter at a time, same workload)",
        "",
        "| Change | Energy | Latency | Power | Temp | Elasticity (latency / energy) |",
        "|---|---|---|---|---|---|",
    ]
    for w in res.whatifs:
        lines.append(
            f"| {w.change} | {w.energy_change_percent:+.0f}% | {w.latency_change_percent:+.0f}% | "
            f"{w.power_change_percent:+.0f}% | {w.temperature_change_c:+.1f} °C | "
            f"{w.elasticity_latency:+.2f} / {w.elasticity_energy:+.2f} |"
        )
    lines += [
        "",
        "## How to prove any of this",
        "",
        "These are what-ifs, not designs. Model the change at architecture level, synthesise the "
        "affected block on an open PDK for power and area, prototype, and finally measure silicon. "
        "The model has no SRAM hierarchy, dataflow or interconnect, so chip-level conclusions are "
        "directional only.",
        "",
    ]
    return "\n".join(lines)


def build_recipe(
    spec: ProjectSpec,
    model: ModelProfile,
    hw: HardwareProfile,
    res: OptimisationResult,
) -> tuple[dict[str, RecipeFile], list[str]]:
    """Files for the recommended configuration, plus honest warnings."""
    best = res.best
    r = best or res.baseline
    cfg = r.config
    warnings = [
        "Generated from templates and not run on a device. Review before use.",
    ]
    if best is None:
        warnings.append(
            "No configuration met every requirement, so these files describe your current "
            "setup, not a fix."
        )
    if r.feasibility.value == "uncertain":
        warnings.append(
            "The recommended setup is uncertain: measure accuracy and performance first."
        )
    files: dict[str, RecipeFile] = {}
    changes = res.recommendation.changes if res.recommendation else ["(no changes)"]
    eco = build_eco(spec, model, hw, cfg)
    if _is_jetson(hw):
        steps = [
            "`bash build_engine.sh` - build the TensorRT engine.",
            "`bash set_power_mode.sh` - set the power mode (look up the id first).",
            "Run your workload, then `bash verify.sh` to measure and report back.",
        ]
    else:
        steps = eco.steps
    onnx_step = (
        [f"`python optimise_model.py` - produce the {cfg.precision.upper()} model."]
        if eco.key != "mcu"
        else []
    )
    files["README.md"] = RecipeFile(
        "Start here: the steps in order",
        "\n".join(
            [
                f"# Recipe: {model.name} on {hw.name}",
                "",
                "Recommended changes:",
                *[f"- {c}" for c in changes],
                "",
                "Steps:",
                *[f"{i}. {t}" for i, t in enumerate(onnx_step + steps, 1)],
                "",
                "Expected (predicted) result is in `runtime_config.json`. Compare it with what you "
                "measure: the Verify tab shows predicted versus measured and calibrates the model.",
                "",
                "**Status:** generated, not executed. " + " ".join(warnings),
            ]
        ),
    )
    if eco.key != "mcu":
        files["optimise_model.py"] = RecipeFile(
            "Convert the model to the recommended precision", _optimise_model_py(cfg, model)
        )
    files["quant_sensitivity.py"] = RecipeFile(
        "Measure which layers are fragile to int8 on your own data (for mixed precision)",
        quant_sensitivity_script(),
    )
    if _is_jetson(hw):
        files["build_engine.sh"] = RecipeFile("Build the TensorRT engine", _build_engine_sh(cfg, model))
        files["set_power_mode.sh"] = RecipeFile("Set the power mode", _power_sh(cfg, hw))
        files["verify.sh"] = RecipeFile("Measure on the board and report back", _verify_sh(spec, cfg))
    else:
        for name, (desc, content) in eco.files.items():
            files[name] = RecipeFile(desc, content)
    files["runtime_config.json"] = RecipeFile(
        "The recommended settings and the predicted result",
        json.dumps(
            {
                "model": model.id,
                "device": hw.id,
                "config": cfg.model_dump(),
                "feasibility": r.feasibility.value,
                "predicted": _metrics(r),
                "requirements": spec.constraints.model_dump(),
                "workload": spec.workload.model_dump(),
                "engine_version": r.engine_version,
            },
            indent=2,
        ),
    )
    files["hardware_design_notes.md"] = RecipeFile(
        "Power budget, thermal requirement and design what-ifs for hardware engineers",
        _design_notes(spec, hw, res),
    )
    return files, warnings
